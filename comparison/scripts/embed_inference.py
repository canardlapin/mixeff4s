#!/usr/bin/env python3
"""Embed the complete canonical R witness without requiring R in default tests."""
import hashlib
import json
from pathlib import Path

root=Path(__file__).resolve().parents[2]
base=root/'comparison/inference-tranche'
source=base/'references.json'
provenance=json.loads((base/'reference-provenance.json').read_text())
assert hashlib.sha256(source.read_bytes()).hexdigest()==provenance['artifacts']['references_json_sha256']
raw=json.dumps(json.loads(source.read_text()),separators=(',',':'),ensure_ascii=False)
assert '"""' not in raw
chunks=[raw[i:i+8000] for i in range(0,len(raw),8000)]
output=root/'src/test/scala/mixeff4s/stats/InferenceFrozen.scala'
output.write_text('package mixeff4s.stats\n\n/** Complete canonical frozen R witness; regenerated by comparison/scripts/embed_inference.py. */\nprivate[mixeff4s] object InferenceFrozen:\n  val json: String = Vector(\n'+',\n'.join('    """'+chunk+'"""' for chunk in chunks)+'\n  ).mkString\n')
print(f'Embedded complete R JSON: {len(raw)} characters in {len(chunks)} chunks')
